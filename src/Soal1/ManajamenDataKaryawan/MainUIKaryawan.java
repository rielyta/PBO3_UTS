    private void DeleteKaryawanBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteKaryawanBtnActionPerformed
        // TODO add your handling code here:
        //Baris dipilih dari tabel
        int selectedRow = tableKaryawan.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih karyawan");
            return;
        }
        //Ambil ID dari tabel
        String KaryawanId = (String) tableKaryawan.getValueAt(selectedRow, 0);
        // Konfirmasi penghapusan
        int confirm = JOptionPane.showConfirmDialog(this,
            "Apakah anda yakin menghapus data ini",
            "", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                boolean deleted = Perusahaan.hapusKaryawan(KaryawanId);
            if (deleted) {
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
                loadKaryawan(); 
            } else {
                JOptionPane.showMessageDialog(this, "Data gagal dihapus");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error" + ex.getMessage());
        }
    }       
    }//GEN-LAST:event_DeleteKaryawanBtnActionPerformed

    private void CariPosisiFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CariPosisiFieldActionPerformed
     // TODO add your handling code here:
    String keyword = CariPosisiField.getText().trim().toLowerCase();
    // Tampilkan semua jika kosong
    if (keyword.isEmpty()) {
        loadKaryawan(); 
        return;
    }
    // Kosongkan tabel
    tableModel.setRowCount(0); 
    for (Karyawan k : Perusahaan.SemuaKaryawan()) {
        if (k.getPosisi().toLowerCase().contains(keyword)) {
            tableModel.addRow(new Object[]{
                k.getId(), k.getNama(), k.getPosisi(), k.getGaji()
            });
        }
    }
    }//GEN-LAST:event_CariPosisiFieldActionPerformed

