    // Menampilkan seluruh data karyawan ke dalam tabel
    private void loadKaryawan() {
    tableModel.setRowCount(0); 
    List<Karyawan> karyawan = Perusahaan.SemuaKaryawan();
    for (Karyawan karyawans : karyawan) {
        tableModel.addRow(new Object[]{
            karyawans.getId(), 
            karyawans.getNama(), 
            karyawans.getPosisi(), 
            karyawans.getGaji(), 
        });
    }
}
