    private void AddKaryawanBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddKaryawanBtnActionPerformed
        // TODO add your handling code here:
        //ambil input dari field
        String id   =  IdKaryawanField.getText().trim();
        String nama =  NamaKaryawanField.getText().trim();
        String posisi = PosisiKaryawanField.getText().trim();
        String gajiStr = GajiKaryawanField.getText().trim().replace(",", ".");
        //Jika ada kolom tidak diisi
        if (id.isEmpty() || nama.isEmpty() || posisi.isEmpty() || gajiStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Id, nama, posisi, gaji harus diisi.");
            return;
        }
        //Validasi Gaji
        double gaji;
        try {
            gaji = Double.parseDouble(gajiStr);
            if (gaji < 0) {
                JOptionPane.showMessageDialog(this, "Gaji tidak boleh negatif");
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Format gaji tidak valid");
            return;
        }
        //Buat objek karyawan baru dan tambahkan ke data perusahaan
        Karyawan newKaryawan = null;
        try {
            newKaryawan = new Karyawan(id, nama, posisi, gaji);
        }  catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
            return;
        }
        boolean success = Perusahaan.tambahKaryawan(newKaryawan);
        JOptionPane.showMessageDialog(this, "Karyawan berhasil ditambahkan!");
        loadKaryawan(); 
        IdKaryawanField.setText("");
        NamaKaryawanField.setText("");
        PosisiKaryawanField.setText(""); 
        GajiKaryawanField.setText("");
    }//GEN-LAST:event_AddKaryawanBtnActionPerformed

    // Fungsi bantu untuk mengambil nilai dari tabel dengan validasi null
    private String safeValueAt(int row, int col, String fieldName) {
    Object val = tableKaryawan.getValueAt(row, col);
    if (val == null) {
        JOptionPane.showMessageDialog(this, "Column " + fieldName + " is invalid");
        throw new NullPointerException("Invalid value in " + fieldName);
    }
    return val.toString();
}
    private void UpdateKaryawanBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateKaryawanBtnActionPerformed
    //baris kolom dalam tabel dipilih terlebih dahulu
    int selectedRow = tableKaryawan.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Pilih Karyawan untuk di-update");
        return;
    }
  
    try {
        //ambil data dari tabel
        String id = safeValueAt(selectedRow, 0, "ID");
        String oldName = safeValueAt(selectedRow, 1, "Nama");
        String oldPosisi = safeValueAt(selectedRow, 2, "Posisi");
        double oldGaji = Double.parseDouble(safeValueAt(selectedRow, 3, "Gaji"));
         // Ambil input baru
        String namaInput = NamaKaryawanField.getText().trim();
        String posisiInput = PosisiKaryawanField.getText().trim();
        String gajiInput = GajiKaryawanField.getText().trim();
        // Gunakan input baru jika ada, atau pertahankan data lama
        String Nama = namaInput.isEmpty() ? oldName : namaInput;
        String Posisi = posisiInput.isEmpty() ? oldPosisi : posisiInput;
        double Gaji = gajiInput.isEmpty() ? oldGaji : Double.parseDouble(gajiInput);
        // Validasi gaji tidak negatif
        if (Gaji < 0) {
            JOptionPane.showMessageDialog(this, "Gaji tidak boleh negatif");
            return;
        }
        // Buat objek karyawan baru untuk update
        Karyawan updateKaryawan = new Karyawan(id, Nama, Posisi, Gaji); // Pastikan konstruktor mendukung ID
        boolean success = Perusahaan.updateKaryawan(updateKaryawan);

        if (success) {
            JOptionPane.showMessageDialog(this, "Data berhasil diubah");
            clearMainUIKaryawan();
            loadKaryawan();
        } else {
            JOptionPane.showMessageDialog(this, "Data gagal diubah");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saat update: " + e.getMessage());
        e.printStackTrace();
    }
    }
