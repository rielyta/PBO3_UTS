    private void AddBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddBtnActionPerformed
        // TODO add your handling code here:
        String jenis = (String) VehicleTypeCbx.getSelectedItem();
        String metode = (String) DurationTypeCbx.getSelectedItem();
        
        Kendaraan kendaraan = new Kendaraan(jenis);
        
        try {
            if (metode.equalsIgnoreCase("Manual")) {
                int durasi = Integer.parseInt(DurationTimeField.getText());
                ParkingService.DurasiManual(kendaraan, durasi);       
            } else {
                int masuk = Integer.parseInt(EntryTimeField.getText());
                int keluar = Integer.parseInt(ExitTimeField.getText());
                ParkingService.DurasiDenganWaktu(kendaraan, masuk, keluar);
            }
            //Update table
            tableModel.addRow(new Object[]{
                kendaraan.getJenis(),
                metode,
                kendaraan.getLamaParkir()+"jam",
                "Rp" + kendaraan.hitungBiaya()
            });
            //update total
            TotalVehicleField.setText(String.valueOf(ParkingService.getDaftarKendaraan().size()));
            TotalFeeField.setText("Rp" + ParkingService.hitungTotalBiaya());
            //Kosongkan input
            DurationTimeField.setText("");
            EntryTimeField.setText("");
            ExitTimeField.setText("");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Masukkan angka yang valid ","Input Error",JOptionPane.ERROR_MESSAGE );
        }
    }//GEN-LAST:event_AddBtnActionPerformed

    private void DurationTypeCbxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DurationTypeCbxActionPerformed
        // TODO add your handling code here:
        String selectedType = (String) DurationTypeCbx.getSelectedItem();
        boolean isManual = "Manual".equalsIgnoreCase(selectedType);
        boolean isTime = "Time".equalsIgnoreCase(selectedType);
        
        DurationTimeField.setEnabled(isManual);
        if (!isManual) {
            DurationTimeField.setText("");
        }
        
        EntryTimeField.setEnabled(isTime);
        ExitTimeField.setEnabled(isTime);
        if (!isTime) {
            EntryTimeField.setText("");
            ExitTimeField.setText("");
        }
    }//GEN-LAST:event_DurationTypeCbxActionPerformed

