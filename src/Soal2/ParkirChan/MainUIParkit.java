    private void loadKendaraan() {
        DefaultTableModel model = (DefaultTableModel) ParkingTable.getModel();
        model.setRowCount(0); // bersihkan tabel

        for (Kendaraan k : ParkingService.getDaftarKendaraan()) {
         model.addRow(new Object[]{
                k.getJenis(),
                (k.getLamaParkir() > 0 ? "Manual/Time" : "-"),
                k.getLamaParkir() + " jam",
                "Rp" + k.hitungBiaya()
            });
        }

        TotalVehicleField.setText(String.valueOf(ParkingService.getDaftarKendaraan().size()));
        TotalFeeField.setText("Rp" + ParkingService.hitungTotalBiaya());
    }
